def clean(p):
    p = re.sub(r'\s*\n\s*', ' ', p)            # hard-wrapped lines in the source
    p = re.sub(r'([a-z])\.(?=[A-Z])', r'\1. ', p)  # "masterplan.Earlier" joins
    return html.escape(p, quote=False)


def person(slug, name, role, photo, bios):
    paras = '\n'.join(f'          <p>{clean(p)}</p>' for p in bios[slug])
    return f'''    <section class="bio" id="{slug}">
      <img class="bio__photo" src="images/web/{photo}.webp" alt="{name}" loading="lazy" decoding="async">
      <div class="bio__text">
        <h2 class="bio__name">{name}</h2>
        <p class="bio__role">{role}</p>
        <div class="bio__body"><div class="bio__inner">
{paras}
        </div></div>
        <button class="bio__more" type="button" aria-expanded="false" aria-controls="{slug}">
          <span class="bio__more-label">See my info</span>
          <img class="bio__more-arrow" src="images/mobile/arrow-link.svg" alt="">
        </button>
      </div>
    </section>'''


